import assert from "node:assert/strict";
import React from "react";
import { renderToString } from "react-dom/server";
import { MemoryRouter } from "react-router-dom";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import RentalPublic from "../src/components/rentals/RentalPublic";
import RentalSettings from "../src/pages/RentalSettings";
import RentalWorkspace from "../src/pages/RentalWorkspace";
import { ThemeProvider } from "../src/contexts/ThemeContext";
import { LanguageProvider } from "../src/contexts/LanguageContext";
import { rentalToday } from "../src/lib/rentalApi";
import { useAuth } from "../src/store/auth";
const today = rentalToday();
const from = `${today.slice(0, 7)}-01`;
const to = `${today.slice(0, 7)}-${new Date(Date.UTC(Number(today.slice(0, 4)), Number(today.slice(5, 7)), 0)).getUTCDate()}`;
const rates = { hourly_price: 2000, min_minutes: 60, max_minutes: 240, buffer_minutes: 0, slot_step_minutes: 30 };
const gallery = [{ id: 1, kind: "image", url: "/api/media/file/space.png", caption: "Main hall", sort_order: 0 }, { id: 2, kind: "video", url: "/api/media/file/tour.mp4", sort_order: 1 }];
const business = { id: 1, slug: "qa-rental", name: "QA Rental", business_type: "rentals", vertical: "rentals", address: "Yerevan", timezone: "Asia/Yerevan", rental: rates, gallery, work_start: "09:00", work_end: "18:00" };
useAuth.setState({ user: { id: 1, name: "QA Owner", email: "qa@example.com", role: "owner", business_id: 1, business_name: "QA Rental", business_slug: "qa-rental", business_type: "rentals", vertical: "rentals", needs_onboarding: false } });
const query = new QueryClient({ defaultOptions: { queries: { retry: false, staleTime: Infinity } } });
query.setQueryData(["rental-public-slots", business.slug, today, 60, false, ""], [{ starts_at: `${today} 16:00`, ends_at: `${today} 17:00`, price: 2000 }]);
query.setQueryData(["rental-profile"], business);
query.setQueryData(["rental-settings"], { ...rates, gallery });
query.setQueryData(["rental-schedule"], []);
query.setQueryData(["rental-bookings", from, to], []);
query.setQueryData(["rental-blocks", from, to], []);
query.setQueryData(["rental-summary", from, to], { bookings_count: 1, booked_amount: 2000, completed_amount: 0, net_received: 500, outstanding_amount: 1500, refunded_amount: 0, refund_due: 0, occupancy_percent: 5, monthly_subscription: 25000, booked_minutes: 60, pending_count: 0, cancelled_count: 0, daily: [] });
function render(Component, route, props = {}) {
  return renderToString(React.createElement(MemoryRouter, { initialEntries: [route] }, React.createElement(QueryClientProvider, { client: query }, React.createElement(ThemeProvider, null, React.createElement(LanguageProvider, null, React.createElement(Component, props))))));
}
const publicPage = render(RentalPublic, "/book/qa-rental", { business });
assert.match(publicPage, /QA Rental/);
assert.match(publicPage, /type="email"/);
assert.match(publicPage, /type="tel"/);
assert.match(publicPage, /16:00/);
assert.match(publicPage, /<video[^>]+controls/);
assert.doesNotMatch(publicPage, /service_id|staff_id/);
const settingsPage = render(RentalSettings, "/app/settings");
assert.match(settingsPage, /25 000/);
assert.match(settingsPage, /video\/mp4/);
assert.match(settingsPage, /type="time"/);
assert.match(render(RentalSettings, "/app/onboarding", { onboarding: true }), /<form/);
assert.match(render(RentalWorkspace, "/app/calendar"), /rental-month-day/);
assert.match(render(RentalWorkspace, "/app/analytics"), /1[\s.,]?500/);
assert.match(render(RentalWorkspace, "/app/dashboard"), /25[\s.,]?000/);
console.log("Rental render checks passed: public form, media gallery, settings, onboarding, calendar, analytics and dashboard.");
query.clear();
