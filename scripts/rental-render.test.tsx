const today = rentalToday();
const from = `${today.slice(0, 7)}-01`;
const to = `${today.slice(0, 7)}-${new Date(Date.UTC(Number(today.slice(0, 4)), Number(today.slice(5, 7)), 0)).getUTCDate()}`;
const rates = { hourly_price: 2000, min_minutes: 60, max_minutes: 10080, buffer_minutes: 0, slot_step_minutes: 30, allow_overnight: true };
const gallery = [{ id: 1, kind: "image", url: "/api/media/file/space.png", caption: "Main hall", sort_order: 0 }, { id: 2, kind: "video", url: "/api/media/file/tour.mp4", sort_order: 1 }];
const business = { id: 1, slug: "qa-rental", name: "QA Rental", business_type: "rentals", vertical: "rentals", address: "Yerevan", timezone: "Asia/Yerevan", rental: rates, gallery, logo_url: "https://api.vizit.am/api/media/file/logo.png", cover_url: "https://api.vizit.am/api/media/file/cover.png", work_start: "09:00", work_end: "18:00" };
useAuth.setState({ user: { id: 1, name: "QA Owner", email: "qa@example.com", role: "owner", business_id: 1, business_name: "QA Rental", business_slug: "qa-rental", business_type: "rentals", vertical: "rentals", needs_onboarding: false } });
const query = new QueryClient({ defaultOptions: { queries: { retry: false, staleTime: Infinity } } });
query.setQueryData(["rental-public-slots", business.slug, today, 60, false, ""], [{ starts_at: `${today} 16:00`, ends_at: `${today} 17:00`, price: 2000 }]);
query.setQueryData(["rental-profile"], business);
query.setQueryData(["public-business-profile", business.slug], business);
query.setQueryData(["rental-settings"], { ...rates, gallery });
query.setQueryData(["rental-schedule"], []);
query.setQueryData(["rental-bookings", from, to], []);
query.setQueryData(["rental-blocks", from, to], []);
query.setQueryData(["rental-summary", from, to], { bookings_count: 1, booked_amount: 2000, completed_amount: 0, net_received: 500, outstanding_amount: 1500, refunded_amount: 0, refund_due: 0, occupancy_percent: 5, monthly_subscription: 25000, booked_minutes: 60, pending_count: 0, cancelled_count: 0, daily: [] });
function render(Component, route, props = {}, routePath = "*") {
  return renderToString(React.createElement(MemoryRouter, { initialEntries: [route] }, React.createElement(QueryClientProvider, { client: query }, React.createElement(ThemeProvider, null, React.createElement(LanguageProvider, null, React.createElement(Routes, null, React.createElement(Route, { path: routePath, element: React.createElement(Component, props) })))))));
}
