import React from "react";
import { renderToString } from "react-dom/server";
import { MemoryRouter, Route, Routes } from "react-router-dom";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import RentalPublic from "../src/components/rentals/RentalPublic";
import RentalProfile from "../src/components/rentals/RentalProfile";
import PublicBusinessProfile from "../src/pages/PublicBusinessProfile";
